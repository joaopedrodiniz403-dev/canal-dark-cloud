import json
import tempfile
import unittest
from pathlib import Path
from nuvem.engine import (authorize, validate_words, candidates, timeline, captions,
                          editorial, produce, qa, run, overlaps)


def fixture(root):
    """Synthetic motion and tone, explicitly NOT an editorial or ASR validation."""
    run(['ffmpeg', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=640x360:rate=30:duration=18',
         '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000:duration=18',
         '-c:v', 'libx264', '-threads', '2', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p',
         '-c:a', 'aac', '-shortest', root / 'motion.mp4'])
    texts = ['Olha', 'como', 'essa', 'cena', 'começa!', 'O', 'personagem', 'correu', 'até', 'o',
             'carro.', 'Mas', 'uma', 'surpresa', 'mudou', 'tudo!', 'No', 'final', 'ele', 'voltou',
             'e', 'resolveu', 'o', 'problema.']
    words = [{'text': t, 'start': round(.5+i*.68, 3), 'end': round(.95+i*.68, 3)} for i,t in enumerate(texts)]
    (root / 'words.json').write_text(json.dumps({'backend': 'synthetic_fixture_not_ASR', 'words': words}))
    return {'sources': [{'path': 'motion.mp4', 'transcript': 'words.json', 'test_only': True,
            'rights': {'verified': True, 'kind': 'owned', 'reference': 'generated by tests/test_engine.py',
                       'holder': 'local test fixture', 'verified_by': 'test generator', 'verified_at': '2026-11-06'}}]}


class UnitTests(unittest.TestCase):
    def test_rights_fail_closed(self):
        with tempfile.TemporaryDirectory() as d:
            with self.assertRaises(ValueError):
                authorize({'path': 'a', 'rights': {'verified': 'true'}}, Path(d))

    def test_path_escape_and_symlink(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d) / 'allowed'
            root.mkdir()
            (Path(d)/'outside').touch()
            (root/'link').symlink_to(Path(d)/'outside')
            for name in ('../outside', 'link'):
                with self.assertRaises(ValueError):
                    from nuvem.engine import local_file
                    local_file(root, name)

    def test_timestamps(self):
        for a,b in [(float('nan'), 1), (1, 0), (0, 11)]:
            with self.assertRaises(ValueError):
                validate_words({'words': [{'text': 'oi', 'start': a, 'end': b}]}, 10)
        with self.assertRaises(ValueError):
            validate_words({'words': [{'text': 'a', 'start': 1, 'end': 3}, {'text': 'b', 'start': 2, 'end': 4}]}, 10)

    def test_gap_timeline(self):
        spans, w = timeline([{'text': 'a', 'start': 1, 'end': 2}, {'text': 'b', 'start': 5, 'end': 6}], .9, 6.1)
        self.assertEqual(spans, [(.9, 2.25), (4.75, 6.1)])
        self.assertAlmostEqual(w[1]['start'], 1.6)
        self.assertAlmostEqual(w[1]['end'], 2.6)

    def test_captions_escape(self):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d)/'captions.ass'
            captions([{'text': r'{\pos(0,0)}', 'start': .1, 'end': .9}], p)
            self.assertNotIn(r'{\pos(0,0)}', p.read_text())
            self.assertIn('0:00:00.10,0:00:00.90', p.read_text())

    def test_candidates_complete_and_bounded(self):
        words = [{'text': 'Olha!' if i % 5 == 4 else 'palavra', 'start': i*.7, 'end': i*.7+.5} for i in range(100)]
        result = candidates(words)
        self.assertTrue(result)
        self.assertTrue(all(12 <= c['end']-c['start'] <= 59 for c in result))
        self.assertTrue(all(c['words'][-1]['text'].endswith('!') for c in result))
        self.assertTrue(all(0 <= c['editorial']['score'] <= 100 for c in result))

    def test_overlap(self):
        self.assertTrue(overlaps({'start': 0, 'end': 20}, {'start': 10, 'end': 30}))

    def test_production_rejects_fixtures(self):
        from nuvem.engine import reject_test_source
        for source, transcript in [({'test_only': True}, {}), ({}, {'backend': 'synthetic_fixture_not_ASR'})]:
            with self.assertRaisesRegex(ValueError, 'TEST_INPUT_REJECTED'):
                reject_test_source(source, transcript)

    def test_empty_queue(self):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d)
            r = produce(p, {'sources': []}, p/'out', p/'state.db')
            self.assertEqual(r['status'], 'EMPTY_QUEUE')
            self.assertFalse(r['publication_enabled'])


class IntegrationTests(unittest.TestCase):
    def test_real_render_qa_and_dedupe(self):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d)
            manifest = fixture(p)
            r = produce(p, manifest, p/'out', p/'state.db', limit=1, allow_internal_test=True)
            self.assertEqual(r['produced'], 1, json.dumps(r))
            self.assertEqual(r['items'][0]['status'], 'TECHNICAL_TEST_ONLY')
            self.assertEqual(r['status'], 'INTERNAL_TESTS_ONLY')
            self.assertEqual(r['ready_for_review'], 0)
            self.assertIsNone(r['items'][0]['editorial']['score'])
            self.assertFalse(r['items'][0]['quality']['editorial_approved'])
            self.assertTrue(r['items'][0]['quality']['passed'])
            again = produce(p, manifest, p/'out2', p/'state.db', limit=5, allow_internal_test=True)
            self.assertEqual(again['produced'], 0)
            item = r['items'][0]
            words = json.loads((p/'out'/item['id']/'words.json').read_text())['words']
            # A silent output must be rejected even if dimensions and container are valid.
            run(['ffmpeg', '-v', 'error', '-y', '-i', p/'out'/item['video'], '-af', 'volume=0',
                 '-c:v', 'copy', '-c:a', 'aac', p/'silent.mp4'])
            self.assertFalse(qa(p/'silent.mp4', words, item['quality']['duration'])['checks']['audio_audible'])


if __name__ == '__main__':
    unittest.main()
